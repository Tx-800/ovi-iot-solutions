/* ==========================================================================
   build-icons.js — generates assets/icons/sprite.svg from lucide-static

   Emits a standalone <symbol> sprite containing only the icons this site
   uses. ARCHITECTURE.md §1: the Lucide UMD bundle ships ~1500 icons and
   breaks the JS budget, so the shipped artefact is a committed sprite with
   zero runtime JavaScript. The artwork is genuine Lucide; only the delivery
   changed.

   The sprite is an EXTERNAL file, referenced from every page as
   <use href="/assets/icons/sprite.svg#i-name">, rather than inlined into
   each page. One request, cached once by the browser across all 16 pages,
   instead of ~6.5KB repeated in every page's HTML. <use> referencing an
   external SVG still inherits color/currentColor from the <use> element
   itself (SVG2 shadow-tree inheritance) — verified in Chrome via
   tools/icon-color-probe.html before this was adopted.

   lucide-static is a devDependency. This script runs at authoring time and
   its output is committed, so the site still works with node_modules deleted.

   Add an icon by adding its Lucide name to ICONS below, then re-run:
     node tools/build-icons.js && node tools/sync-partials.js
   ========================================================================== */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const ICON_DIR = join(ROOT, 'node_modules', 'lucide-static', 'icons');
const OUT = join(ROOT, 'assets', 'icons', 'sprite.svg');

/* Every icon used on the site, with where it is used. DESIGN.md §7 names most
   of these; keep this list honest — an unused icon is dead weight on 16 pages. */
const ICONS = {
  /* UI chrome */
  'menu':               'drawer toggle',
  'x':                  'drawer close',
  'chevron-down':       'mega-menu disclosure',
  'arrow-up':           'back to top',
  'message-circle':     'WhatsApp FAB',
  'copy':               'copy email',
  'check':              'copy confirmation',
  /* Solutions — DESIGN.md §7 */
  'gauge':              'smart water metering',
  'lightbulb':          'smart street lighting',
  'droplets':           'water leak detection',
  'flask-conical':      'water quality monitoring',
  'waves':              'water level monitoring',
  'map-pin':            'people and asset tracking',
  'shield-alert':       'ATEX zone sensors',
  'compass':            'RF planning',
  'file-text':          'consultancy and tender preparation',
  /* Architecture diagram + pillars */
  'radio-tower':        'gateways',
  'server':             'network server',
  'monitor-smartphone': 'applications',
  'cpu':                'end devices',
  'network':            'dual connectivity pillar',
  'route':              'end-to-end delivery pillar',
  'building-2':         'multi-sector reach pillar',
  'wrench':             'industrial grade',
  'handshake':          'advisory partner',
  /* Phase 4 — solution and service detail page capability/sensor/service cards */
  'toggle-right':       'remote control (street lighting)',
  'zap':                'energy monitoring (street lighting)',
  'alert-triangle':     'fault detection (street lighting)',
  'calendar-clock':     'maintenance planning (street lighting)',
  'thermometer':        'temperature monitoring (ATEX)',
  'activity':           'vibration monitoring (ATEX)',
  'sliders-horizontal':  'valve positioning (ATEX)',
  'clipboard-check':    'feasibility studies (consultancy)',
  'scale':              'vendor and technology evaluation (consultancy)',
  'signal':             'on-site signal surveys (RF planning)',
  'radar':              'coverage simulation (RF planning)',
};

const missing = [];
const symbols = [];

for (const [name, usage] of Object.entries(ICONS)) {
  const file = join(ICON_DIR, `${name}.svg`);
  if (!existsSync(file)) { missing.push(name); continue; }

  const svg = readFileSync(file, 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .join('');

  if (!inner) { missing.push(name); continue; }
  symbols.push(`  <symbol id="i-${name}" viewBox="0 0 24 24"><!-- ${usage} -->${inner}</symbol>`);
}

if (missing.length) {
  console.error(`build-icons: not found in lucide-static: ${missing.join(', ')}`);
  process.exit(1);
}

const version = JSON.parse(
  readFileSync(join(ROOT, 'node_modules', 'lucide-static', 'package.json'), 'utf8')
).version;

const out = `<?xml version="1.0" encoding="UTF-8"?>
<!-- assets/icons/sprite.svg — GENERATED by tools/build-icons.js. Do not edit by hand.
     Lucide ${version}, ISC licensed. Only the ${symbols.length} icons this site actually uses.
     Stroke width, size and colour come from the .icon class in css/05-components.css applied to
     the <use> element — SVG2 shadow-tree inheritance passes currentColor down into each symbol.
     No style attribute on the root: <symbol> never renders on its own, and the CSP allows no
     inline style. -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join('\n')}
</svg>
`;

writeFileSync(OUT, out, 'utf8');
console.log(`build-icons: ${symbols.length} icons -> assets/icons/sprite.svg (lucide-static ${version})`);
