/* ==========================================================================
   build-sitemap.js — writes sitemap.xml from the pages on disk, using SITE.url
   as the origin, and points robots.txt at it.

   Every page except 404.html (which is noindex). <lastmod> is the date of the
   page's last git commit — a real date, not today's — and is left out when
   git is unavailable rather than guessed.

   Refuses to run while SITE.url is a placeholder: a sitemap full of
   placeholder URLs is worse than none, and the exit code is non-zero so a
   deploy script cannot mistake "skipped" for "done".

   Usage:
     node tools/build-sitemap.js           # write sitemap.xml and robots.txt
     node tools/build-sitemap.js --check   # exit 1 if either is missing or stale
   ========================================================================== */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { SITE } from '../js/site.config.js';

const ROOT = resolve(import.meta.dirname, '..');
const SKIP_DIRS = new Set(['docs', 'node_modules', '.git', 'partials', 'tools', '.shots', 'dist']);
const EXCLUDE = new Set(['404.html']);
const CHECK_ONLY = process.argv.includes('--check');

/* Matched loosely on purpose: the literal placeholder string must not appear
   anywhere outside js/site.config.js (PRD.md §11). */
if (!SITE.url || /REPLACE/i.test(SITE.url)) {
  console.error('build-sitemap: ✗ SITE.url in js/site.config.js is still a placeholder.');
  console.error('  Set the production domain, then run this again. Nothing was written.');
  process.exit(1);
}

const origin = SITE.url.replace(/\/+$/, '');

function htmlFiles(dir = ROOT, found = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(entry) && !entry.startsWith('.')) htmlFiles(full, found);
    } else if (entry.endsWith('.html')) {
      found.push(relative(ROOT, full).replaceAll('\\', '/'));
    }
  }
  return found;
}

function lastCommitDate(rel) {
  try {
    return execFileSync('git', ['log', '-1', '--format=%cs', '--', rel], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

const pages = htmlFiles().filter((rel) => !EXCLUDE.has(rel)).sort((a, b) => {
  /* Home first, then section indexes, then detail pages. */
  const rank = (p) => (p === 'index.html' ? 0 : p.includes('/') ? 2 : 1);
  return rank(a) - rank(b) || a.localeCompare(b);
});

const urls = pages.map((rel) => {
  const loc = rel === 'index.html' ? `${origin}/` : `${origin}/${rel}`;
  const date = lastCommitDate(rel);
  return `  <url>\n    <loc>${loc}</loc>${date ? `\n    <lastmod>${date}</lastmod>` : ''}\n  </url>`;
});

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by tools/build-sitemap.js. Do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls,
  '</urlset>',
  '',
].join('\n');

/* robots.txt is committed; only its Sitemap line is generated. */
const robotsPath = join(ROOT, 'robots.txt');
const robotsBase = existsSync(robotsPath)
  ? readFileSync(robotsPath, 'utf8').replace(/^Sitemap:.*\n?/gm, '').replace(/\n+$/, '\n')
  : 'User-agent: *\nAllow: /\n';
const robots = `${robotsBase}\nSitemap: ${origin}/sitemap.xml\n`;

const sitemapPath = join(ROOT, 'sitemap.xml');
const current = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);

if (CHECK_ONLY) {
  /* lastmod moves with every commit, so compare the URL set, not the bytes. */
  const locs = (xml) => (xml.match(/<loc>[^<]*<\/loc>/g) || []).join('\n');
  const problems = [];
  const have = current(sitemapPath);
  if (have === null) problems.push('sitemap.xml is missing');
  else if (locs(have) !== locs(sitemap)) problems.push('sitemap.xml lists a different set of pages, or another domain');
  if (current(robotsPath) !== robots) problems.push('robots.txt does not point at this sitemap');
  if (problems.length) {
    for (const p of problems) console.error(`build-sitemap: ✗ ${p}`);
    console.error('  Run: node tools/build-sitemap.js');
    process.exit(1);
  }
  console.log(`build-sitemap: sitemap.xml and robots.txt are current (${pages.length} pages).`);
  process.exit(0);
}

writeFileSync(sitemapPath, sitemap, 'utf8');
writeFileSync(robotsPath, robots, 'utf8');
console.log(`build-sitemap: ${pages.length} page(s) -> sitemap.xml; robots.txt points at ${origin}/sitemap.xml`);
