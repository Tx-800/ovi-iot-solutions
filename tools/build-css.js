/* ==========================================================================
   build-css.js — concatenates css/src/01..08 into the single css/main.css

   Why this exists: main.css used to @import the eight source files. That
   costs a render-blocking request waterfall — the browser cannot discover the
   eight until main.css has arrived — and Lighthouse measured it at ~450ms of
   blocked rendering on mobile, which put Performance under the PRD N1 gate.

   The authored split in css/src/ is unchanged and is still the source of
   truth; main.css is a generated artefact that is committed, so the site
   still serves correctly with node_modules deleted and needs no build step to
   run. Same pattern as tools/build-icons.js (ARCHITECTURE.md §1).

   Import order is the cascade — the ORDER array below is that order.

   Usage: node tools/build-css.js [--check]
   ========================================================================== */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const SRC = join(ROOT, 'css', 'src');
const OUT = join(ROOT, 'css', 'main.css');
const CHECK_ONLY = process.argv.includes('--check');

const LAYERS = 'reset, base, layout, components, sections, pages, utilities';

/* file -> layer. `null` means unlayered on purpose: a token definition should
   outrank every layered rule, and unlayered normal declarations do. */
const ORDER = [
  ['00-fonts.css', null],
  ['01-reset.css', 'reset'],
  ['02-tokens.css', null],
  ['03-base.css', 'base'],
  ['04-layout.css', 'layout'],
  ['05-components.css', 'components'],
  ['06-sections.css', 'sections'],
  ['07-pages.css', 'pages'],
  ['08-utilities.css', 'utilities'],
];

const indent = (text) => text.split('\n').map((l) => (l.trim() ? `  ${l}` : l)).join('\n');

const parts = [
  '/* ==========================================================================',
  '   main.css — GENERATED by tools/build-css.js. Do not edit by hand.',
  '',
  '   Sources are css/src/*.css, concatenated in cascade order. Edit those,',
  '   then run: node tools/build-css.js',
  '',
  '   This is one file rather than a chain of @import rules because the chain',
  '   blocked rendering on a second round trip. Comments are kept: with no',
  '   build step they are the only documentation, and they compress away.',
  '   ========================================================================== */',
  '',
  `@layer ${LAYERS};`,
  '',
];

for (const [file, layer] of ORDER) {
  const body = readFileSync(join(SRC, file), 'utf8').replace(/\s*$/, '');

  if (/@import\b/.test(body)) {
    console.error(`build-css: ${file} contains an @import, which would re-create the waterfall.`);
    process.exit(1);
  }

  parts.push(`/* ===== css/src/${file} ${layer ? `-> @layer ${layer}` : '-> unlayered'} ===== */`);
  parts.push('');
  parts.push(layer ? `@layer ${layer} {\n${indent(body)}\n}` : body);
  parts.push('');
}

const out = parts.join('\n');

if (CHECK_ONLY) {
  const current = readFileSync(OUT, 'utf8');
  if (current === out) {
    console.log('build-css: main.css is up to date.');
    process.exit(0);
  }
  console.error('build-css: main.css is STALE — run node tools/build-css.js');
  process.exit(1);
}

writeFileSync(OUT, out, 'utf8');

const bytes = Buffer.byteLength(out);
const gz = (await import('node:zlib')).gzipSync(Buffer.from(out), { level: 9 }).length;
console.log(`build-css: ${ORDER.length} sources -> css/main.css`);
console.log(`  ${(bytes / 1024).toFixed(1)} KB uncompressed, ${(gz / 1024).toFixed(1)} KB gzipped (budget 22 KB gzipped)`);
if (gz > 22 * 1024) { console.error('  OVER BUDGET'); process.exit(1); }
