/* ==========================================================================
   build-headers.js — security headers and 404 routing for every supported
   host, generated from one definition so the four files cannot drift.

     _headers        Netlify and Cloudflare Pages (read from dist/)
     netlify.toml    Netlify build settings: build command, publish dist/
     vercel.json     Vercel: build command, output dist/, headers
     .htaccess       Apache / cPanel: headers, ErrorDocument 404, MIME types

   Keep the files for the host you deploy to and delete the rest;
   tools/check-release.js fails until exactly one host's set remains.
   404 routing: Netlify, Cloudflare Pages and Vercel all serve /404.html for
   a missing path automatically when it sits at the root of the output, so
   only Apache needs an explicit ErrorDocument line.

   The Content-Security-Policy allows no inline script and no inline style.
   The one inline block on the site — the <noscript><style> that undoes the
   drawer layout without JavaScript (partials/head.html) — is allowed by its
   sha256 hash, computed here from the shipped HTML. Edit that block and the
   hash changes: re-run this script (check-release.js catches it if not).
   JSON-LD <script type="application/ld+json"> blocks are data, not script,
   and CSP does not apply to them.

   Usage:
     node tools/build-headers.js           # write whichever host files exist (all four on first run)
     node tools/build-headers.js --check   # exit 1 if any present file is stale
   ========================================================================== */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CHECK_ONLY = process.argv.includes('--check');

/* --- The one inline style ------------------------------------------------- */

const index = readFileSync(join(ROOT, 'index.html'), 'utf8');
const noscriptStyle = index.match(/<noscript>\s*<style>([\s\S]*?)<\/style>/);
if (!noscriptStyle) {
  console.error('build-headers: no <noscript><style> found in index.html — has partials/head.html changed?');
  process.exit(1);
}
const styleHash = `'sha256-${createHash('sha256').update(noscriptStyle[1], 'utf8').digest('base64')}'`;

/* --- The policy ------------------------------------------------------------ */

const JSDELIVR = 'https://cdn.jsdelivr.net';          /* Motion (ES module), Leaflet JS/CSS/marker images */
const WEB3FORMS = 'https://api.web3forms.com';        /* enquiry form: fetch and no-JS POST */
const OSM_TILES = 'https://tile.openstreetmap.org';   /* map tiles; map.js uses this host only */

const CSP = [
  "default-src 'self'",
  `script-src 'self' ${JSDELIVR}`,
  `style-src 'self' ${JSDELIVR} ${styleHash}`,
  `img-src 'self' ${JSDELIVR} ${OSM_TILES}`,
  "font-src 'self'",
  `connect-src 'self' ${WEB3FORMS}`,
  `form-action 'self' ${WEB3FORMS}`,
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const HEADERS = [
  ['Content-Security-Policy', CSP],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()'],
  /* frame-ancestors supersedes this; kept for browsers that predate it. */
  ['X-Frame-Options', 'DENY'],
];

const BUILD = 'node tools/build-dist.js';
const GENERATED = 'Generated by tools/build-headers.js. Edit that file, not this one.';

/* --- One file per host ----------------------------------------------------- */

const files = {
  _headers: [
    `# ${GENERATED}`,
    '# Netlify and Cloudflare Pages. Copied into dist/ by tools/build-dist.js.',
    '/*',
    ...HEADERS.map(([k, v]) => `  ${k}: ${v}`),
    '',
  ].join('\n'),

  'netlify.toml': [
    `# ${GENERATED}`,
    '# Netlify build settings. Headers live in _headers, which Netlify reads from dist/.',
    '# 404: Netlify serves dist/404.html for any missing path, with status 404.',
    '[build]',
    `  command = "${BUILD}"`,
    '  publish = "dist"',
    '',
  ].join('\n'),

  'vercel.json': `${JSON.stringify({
    $comment: `${GENERATED} 404: Vercel serves dist/404.html for any missing path, with status 404.`,
    framework: null,
    buildCommand: BUILD,
    outputDirectory: 'dist',
    cleanUrls: false,
    headers: [{ source: '/(.*)', headers: HEADERS.map(([key, value]) => ({ key, value })) }],
  }, null, 2)}\n`,

  '.htaccess': [
    `# ${GENERATED}`,
    '# Apache / cPanel. Upload the CONTENTS of dist/ (this file included) to public_html.',
    '',
    'ErrorDocument 404 /404.html',
    'Options -Indexes',
    '',
    '<IfModule mod_headers.c>',
    ...HEADERS.map(([k, v]) => `  Header always set ${k} "${v}"`),
    '</IfModule>',
    '',
    '# Older Apache builds do not know these types; a wrong type breaks nosniff.',
    'AddType application/manifest+json .webmanifest',
    'AddType image/webp .webp',
    'AddType font/woff2 .woff2',
    'AddType text/javascript .js',
    '',
    '<IfModule mod_deflate.c>',
    '  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/json',
    '  AddOutputFilterByType DEFLATE image/svg+xml application/manifest+json application/xml text/plain',
    '</IfModule>',
    '',
  ].join('\n'),
};

/* --- Write or check -------------------------------------------------------- */

/* After the host is chosen and the others deleted, only the survivors are
   regenerated: deleting a file is how you say you are not using that host. */
const anyPresent = Object.keys(files).some((name) => existsSync(join(ROOT, name)));
const targets = Object.keys(files).filter((name) => !anyPresent || existsSync(join(ROOT, name)));

if (CHECK_ONLY) {
  const stale = targets.filter((name) => readFileSync(join(ROOT, name), 'utf8') !== files[name]);
  if (stale.length) {
    console.error(`build-headers: ✗ stale: ${stale.join(', ')} — run: node tools/build-headers.js`);
    process.exit(1);
  }
  console.log(`build-headers: ${targets.join(', ')} current (style hash ${styleHash}).`);
  process.exit(0);
}

for (const name of targets) writeFileSync(join(ROOT, name), files[name], 'utf8');
console.log(`build-headers: wrote ${targets.join(', ')}`);
console.log(`  CSP style hash for the <noscript> block: ${styleHash}`);
